std::string ProjectGenerator::build_guest_source() const {
  const auto heap_base = choose_heap_base(executable_, configuration_);
  const auto stack_top = choose_stack_top(executable_, configuration_, heap_base);
  const auto entry_point_rva = configuration_.entry_point_rva.value_or(executable_.entry_point_rva);

  std::ostringstream stream;
  stream << "// Generated by recomp-studio. Do not edit.\n";
  stream << "#include \"recomp_runtime.hpp\"\n\n";
  stream << "using namespace recomp;\n\n";
  stream << lifter_.lift_all_functions(configuration_.strict_lifting,
                                       configuration_.source_style == "readable") << "\n";

  stream << "static const GuestFunctionDescriptor recompiled_functions[] = {\n";
  for (const auto& [address, function] : discovery_.functions()) {
    (void)function;
    stream << "  {" << format_hex(address) << ", guest_function_" << std::hex << address << std::dec << "},\n";
  }
  if (discovery_.functions().empty()) stream << "  {0, nullptr},\n";
  stream << "};\n\n";

  stream << "static const GuestImportDescriptor imported_symbols[] = {\n";
  for (const auto& imported : executable_.imports) {
    stream << "  {0x" << std::hex << imported.import_address_table_rva << std::dec
           << ", " << (executable_.is_64_bit ? 8 : 4) << ", " << quote(imported.library_name) << ", "
           << quote(imported.symbol_name) << "},\n";
  }
  if (executable_.imports.empty()) stream << "  {0, 8, \"\", \"\"},\n";
  stream << "};\n\n";

  stream << emit_byte_array(loaded_image_.image_bytes) << "\n";

  stream << "static const RecompiledImage recompiled_image = {\n";
  stream << "  .image_base = " << format_hex(executable_.image_base) << ",\n";
  stream << "  .pointer_width = " << (executable_.is_64_bit ? 8 : 4) << ",\n";
  stream << "  .image_size = " << loaded_image_.image_bytes.size() << ",\n";
  stream << "  .entry_point_rva = 0x" << std::hex << entry_point_rva << std::dec << ",\n";
  stream << "  .stack_top = " << format_hex(stack_top) << ",\n";
  stream << "  .heap_base = " << format_hex(heap_base) << ",\n";
  stream << "  .image_blob = recompiled_image_blob,\n";
  stream << "  .image_blob_size = " << loaded_image_.image_bytes.size() << ",\n";
  stream << "  .function_count = " << (discovery_.functions().empty() ? 1 : discovery_.functions().size()) << ",\n";
  stream << "  .functions = recompiled_functions,\n";
  stream << "  .import_count = " << (executable_.imports.empty() ? 1 : executable_.imports.size()) << ",\n";
  stream << "  .imports = imported_symbols,\n";
  stream << "};\n\n";
  stream << "int main() { return run_recompiled_image(&recompiled_image); }\n";
  return stream.str();
}

GeneratedProject ProjectGenerator::generate(const std::filesystem::path& output_directory) const {
  std::filesystem::create_directories(output_directory);
  GeneratedProject project;
  project.guest_source = output_directory / "guest.cpp";
  {
    std::ofstream output(project.guest_source);
    if (!output) throw std::runtime_error("cannot write generated source");
    output << build_guest_source();
  }

  const auto runtime_directory = configuration_.runtime_directory;
  for (const auto name : {"recomp_runtime.hpp", "recomp_runtime.cpp", "win32_abi.hpp",
                          "guest_file_system.hpp", "upstream_scanf.c",
                          "scanf.h", "hisahi-scanf-LICENSE", "igi-recomp-LICENSE",
                          "cricket07-browser-LICENSE"}) {
    const auto source = runtime_directory / name;
    const auto destination = output_directory / name;
    std::ofstream output(destination, std::ios::binary);
    if (!output) throw std::runtime_error("cannot write " + destination.string());
    output << read_file(source);
    project.runtime_sources.push_back(destination);
  }

  project.image_base = executable_.image_base;
  project.heap_base = choose_heap_base(executable_, configuration_);
  project.stack_top = choose_stack_top(executable_, configuration_, project.heap_base);
  project.function_count = discovery_.functions().size();
  project.import_count = executable_.imports.size();
  project.high_level_function_count = lifter_.high_level_function_count();
  return project;
}

