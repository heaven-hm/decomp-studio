#!/usr/bin/env python3
"""Generate the complete unresolved-import inventory for a Windows PE corpus.

The report deliberately separates native PE inputs from managed/unsupported
inputs: an absent Win32 shim is actionable, while IL bytecode or a foreign
guest architecture needs a frontend instead of another runtime entry.
"""

from __future__ import annotations

import argparse
import json
import subprocess
from collections import Counter
from pathlib import Path


def markdown_cell(value: str) -> str:
    return value.replace("|", "\\|").replace("`", "\\`")


def inspect(cli: Path, executable: Path) -> tuple[dict | None, str]:
    completed = subprocess.run(
        [str(cli), "imports", str(executable), "--json"], text=True, capture_output=True
    )
    if completed.returncode != 0:
        diagnostic_lines = (completed.stderr or completed.stdout).strip().splitlines()
        return None, diagnostic_lines[-1] if diagnostic_lines else "imports exited without a diagnostic"
    try:
        return json.loads(completed.stdout), ""
    except json.JSONDecodeError as error:
        return None, f"invalid imports JSON: {error}"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cli", type=Path, required=True, help="built recomp-studio executable")
    parser.add_argument("--corpus", type=Path, required=True, help="directory containing .exe inputs")
    parser.add_argument("--output", type=Path, default=Path("SHIM_INVENTORY.md"))
    arguments = parser.parse_args()

    executables = sorted(path for path in arguments.corpus.rglob("*")
                       if path.is_file() and path.suffix.lower() == ".exe")
    if not executables:
        raise SystemExit(f"no .exe files found below {arguments.corpus}")

    complete: list[tuple[Path, dict]] = []
    incomplete: list[tuple[Path, dict]] = []
    refused: list[tuple[Path, str]] = []
    symbol_frequency: Counter[str] = Counter()
    symbol_consumers: dict[str, set[str]] = {}

    for index, executable in enumerate(executables, start=1):
        result, diagnostic = inspect(arguments.cli, executable)
        relative = executable.relative_to(arguments.corpus).as_posix()
        print(f"[{index}/{len(executables)}] {relative}", flush=True)
        if result is None:
            refused.append((executable, diagnostic))
            continue
        missing_symbols = [f"{item['library']}!{item['symbol']}" for item in result["missing"]]
        for symbol in missing_symbols:
            symbol_frequency[symbol] += 1
            symbol_consumers.setdefault(symbol, set()).add(relative)
        (complete if result["missing_count"] == 0 else incomplete).append((executable, result))

    lines = [
        "# Complete Shim Inventory",
        "",
        "Generated by `scripts/shim_inventory.py` from the supplied corpus and the current runtime.",
        "It is an import-compatibility inventory, not a runtime-success claim: an app with zero",
        "missing imports can still fail lifting, build, GUI behavior, or differential verification.",
        "",
        "## Summary",
        "",
        "| Measure | Count |",
        "| --- | ---: |",
        f"| PE files inspected | {len(executables)} |",
        f"| Native import-complete inputs | {len(complete)} |",
        f"| Inputs with missing imports | {len(incomplete)} |",
        f"| Refused/non-native inputs | {len(refused)} |",
        f"| Unique unresolved symbols | {len(symbol_frequency)} |",
        "",
        "## All unresolved symbols, priority-ranked",
        "",
        "Frequency is the number of corpus inputs that import the symbol. Consumers are listed",
        "so a shim can be validated against representative applications rather than just a count.",
        "",
        "| Missing import | Apps | Consumers |",
        "| --- | ---: | --- |",
    ]
    for symbol, frequency in symbol_frequency.most_common():
        consumers = ", ".join(sorted(symbol_consumers[symbol]))
        lines.append(f"| `{markdown_cell(symbol)}` | {frequency} | `{markdown_cell(consumers)}` |")

    lines += ["", "## Per-app unresolved imports", "",
              "| Input | Guest arch | Imports | Missing | Unresolved imports |",
              "| --- | --- | ---: | ---: | --- |"]
    for executable, result in incomplete:
        relative = executable.relative_to(arguments.corpus).as_posix()
        missing = ", ".join(f"{item['library']}!{item['symbol']}" for item in result["missing"])
        lines.append(
            f"| `{markdown_cell(relative)}` | {result['architecture']} | {result['import_count']} | "
            f"{result['missing_count']} | `{markdown_cell(missing)}` |"
        )

    lines += ["", "## Import-complete inputs", "",
              "These are candidates for lifting/build/run verification, not automatically verified ports.",
              "", "| Input | Guest arch | Imports |", "| --- | --- | ---: |"]
    for executable, result in complete:
        relative = executable.relative_to(arguments.corpus).as_posix()
        lines.append(f"| `{markdown_cell(relative)}` | {result['architecture']} | {result['import_count']} |")

    if refused:
        lines += ["", "## Refused or non-native inputs", "",
                  "These require a frontend or unpacking change; adding a Win32 shim will not resolve them.",
                  "", "| Input | Diagnostic |", "| --- | --- |"]
        for executable, diagnostic in refused:
            relative = executable.relative_to(arguments.corpus).as_posix()
            lines.append(f"| `{markdown_cell(relative)}` | {markdown_cell(diagnostic)} |")

    arguments.output.write_text("\n".join(lines) + "\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
